function getLocalCardImage(name) {
    if (!name) return "images/logo_clash_royale.png";
    const clean = String(name).toLowerCase().trim().replace(/[-_]+/g, " ");
    if (CARD_LOCAL_MAP[clean]) {
        return CARD_LOCAL_MAP[clean];
    }
    // Recherche par mot-clé si non trouvé exactement
    for (const [key, path] of Object.entries(CARD_LOCAL_MAP)) {
        if (clean.includes(key) || key.includes(clean)) {
            return path;
        }
    }
    return "images/logo_clash_royale.png";
}
